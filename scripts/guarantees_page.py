#!/usr/bin/env python3
"""Generate docs/guarantees.md from the verification coverage registry.

The registry is the only source: every claim appears with the evidence level
the registry records for each layer, and nothing appears without it. Run with
--check to fail when the committed page differs from a fresh render
(test_guarantees_page.py also asserts this).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = "verification/coverage-v1/coverage.json"
PAGE = "docs/guarantees.md"

# Headline order, strongest first. Each status keeps its registry name; the
# headline only picks which layer's status leads the row.
HEADLINE = (
    ("proof", "implementation_proved", "proved (implementation)"),
    ("proof", "reference_proved", "proved (reference model)"),
    ("model", "exhaustive_bounded", "bounded-checked (exhaustive)"),
    ("runtime", "exhaustive_bounded", "bounded-checked (exhaustive)"),
    ("model", "bounded_model_checked", "bounded-checked (model)"),
    ("model", "bounded_static_checked", "bounded-checked (static)"),
    ("runtime", "tested", "tested"),
    ("runtime", "tested-under-simulation", "tested (simulation)"),
    ("model", "executable_reference", "executable reference"),
)
LAYERS = ("runtime", "model", "proof")


def headline(claim: dict) -> str:
    for layer, status, label in HEADLINE:
        if claim.get(layer) == status:
            return label
    if any(claim.get(layer) == "partial" for layer in LAYERS):
        return "partial"
    if all(claim.get(layer) == "deferred" for layer in LAYERS):
        return "deferred"
    return "no evidence"


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def artifacts(claim: dict) -> str:
    seen = []
    for layer in LAYERS:
        for item in claim.get("evidence", {}).get(layer, []):
            path = item.get("artifact")
            if path and path not in seen:
                seen.append(path)
    return "<br>".join(f"`{path}`" for path in seen) or "none"


def render(registry: dict) -> str:
    vocabulary = registry["statusVocabulary"]
    definitions = registry["statusDefinitions"]
    claims = [(subsystem, claim) for subsystem in registry["subsystems"] for claim in subsystem["obligationClaims"]]
    counts: dict[str, int] = {}
    for _, claim in claims:
        counts[headline(claim)] = counts.get(headline(claim), 0) + 1
    order = list(dict.fromkeys([label for _, _, label in HEADLINE] + ["partial", "deferred", "no evidence"]))
    lines = [
        "<!-- Generated by scripts/guarantees_page.py from verification/coverage-v1/coverage.json. Do not edit. -->",
        "",
        "# Guarantees",
        "",
        "What Norn claims about its kernel and runtime, and how strongly each claim is backed. "
        "Every row comes from the verification coverage registry and reports exactly the statuses and evidence artifacts recorded there, including rows that have none.",
        "",
        f"> **Claim policy:** {registry['claimPolicy']}",
        "",
        f"**{len(claims)} obligations** across **{len(registry['subsystems'])} subsystems**. "
        "The headline is the strongest layer the registry records; the three layer columns show each status as recorded.",
        "",
        "| Headline evidence | Obligations |",
        "| --- | ---: |",
    ]
    lines += [f"| {label} | {counts[label]} |" for label in order if label in counts]
    for subsystem in registry["subsystems"]:
        lines += ["", f"## `{subsystem['id']}`", ""]
        if subsystem.get("limitations"):
            limitations = subsystem["limitations"]
            text = " ".join(limitations) if isinstance(limitations, list) else str(limitations)
            lines += [f"*Limitations:* {cell(text)}", ""]
        lines += [
            "| Obligation | Headline | Runtime | Model | Proof | Evidence artifacts |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for claim in subsystem["obligationClaims"]:
            lines.append(
                f"| `{claim['id']}` | {headline(claim)} | {claim['runtime']} | {claim['model']} | {claim['proof']} | {artifacts(claim)} |"
            )
        lines += ["", "<details><summary>What is not covered</summary>", ""]
        lines += [f"- `{claim['id']}`: {cell(claim['residual'])}" for claim in subsystem["obligationClaims"]]
        lines += ["", "</details>"]
    lines += ["", "## Evidence levels", "", "| Status | Meaning |", "| --- | --- |"]
    lines += [f"| `{status}` | {cell(definitions[status])} |" for status in vocabulary]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed page is stale")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    root = args.root.resolve()
    page = render(json.loads((root / REGISTRY).read_text(encoding="utf-8")))
    target = root / PAGE
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != page:
            print(f"{PAGE} is stale; run: python3 scripts/guarantees_page.py", file=sys.stderr)
            return 1
        print(f"{PAGE} matches {REGISTRY}")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(page, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
