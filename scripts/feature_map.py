def _surface_family(surface: str) -> str:
    return surface.split(":", 1)[0]


def render_generated_views(
    domains: dict[str, dict],
    extracted: dict[str, set[str]],
    gate_meta: dict[str, dict],
) -> dict[str, str]:
    """Render `.claude/skills/verify-norn/features/{README.md,<domain>.md}`."""
