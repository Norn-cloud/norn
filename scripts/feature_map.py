def _resolve(schema: dict, root: dict) -> dict:
    seen: set[str] = set()
    while "$ref" in schema:
        ref = schema["$ref"]
        if ref in seen:
            raise FeatureMapError(f"schema: cyclic $ref {ref}")
        seen.add(ref)
        if not ref.startswith("#/"):
            raise FeatureMapError(f"schema: only local $ref is supported, got {ref}")
        node = root
        for part in ref[2:].split("/"):
            node = node[part]
        schema = node
    return schema


def _type_ok(value, name: str) -> bool:
    if name == "integer":
        return isinstance(value, int) and not isinstance(value, bool)
    expected = TYPES[name]
    if expected is not bool and isinstance(value, bool):
        return False
    return isinstance(value, expected)


def validate_schema(value, schema: dict, root: dict, where: str, errors: list[str]) -> None:
    """Validate `value` against the JSON Schema subset used by `schema.json`."""
    schema = _resolve(schema, root)
    if "anyOf" in schema:
        for option in schema["anyOf"]:
            trial: list[str] = []
            validate_schema(value, option, root, where, trial)
            if not trial:
                break
        else:
            errors.append(f"{where}: matches no allowed form")
        return
    if "const" in schema and value != schema["const"]:
        errors.append(f"{where}: must be {schema['const']!r}")
    if "enum" in schema and value not in schema["enum"]:
        errors.append(f"{where}: {value!r} is not one of {schema['enum']}")
    if "type" in schema:
        names = schema["type"] if isinstance(schema["type"], list) else [schema["type"]]
        if not any(_type_ok(value, name) for name in names):
            errors.append(f"{where}: expected {' or '.join(names)}")
            return
    if isinstance(value, str):
        if len(value) < schema.get("minLength", 0):
            errors.append(f"{where}: must not be empty")
        pattern = schema.get("pattern")
        if pattern is not None and pattern.endswith("$") and not pattern.endswith("\\$"):
            pattern = pattern[:-1] + r"\Z"
        if pattern is not None and not re.search(pattern, value):
            errors.append(f"{where}: {value!r} does not match {schema['pattern']}")
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            errors.append(f"{where}: needs at least {schema['minItems']} item(s)")
        if schema.get("uniqueItems"):
            seen = [json.dumps(item, sort_keys=True) for item in value]
            if len(seen) != len(set(seen)):
                errors.append(f"{where}: items must be unique")
        if "items" in schema:
            for index, item in enumerate(value):
                validate_schema(item, schema["items"], root, f"{where}[{index}]", errors)
    if isinstance(value, dict):
        properties = schema.get("properties", {})
        for key in schema.get("required", []):
            if key not in value:
                errors.append(f"{where}: missing {key}")
        for key, item in value.items():
            if key in properties:
                validate_schema(item, properties[key], root, f"{where}.{key}", errors)
            elif schema.get("additionalProperties") is False:
                errors.append(f"{where}: unknown field {key}")


