def _has_symlink_component(root: Path, rel: Path) -> bool:
    cur = root
    for part in rel.parts:
        cur = cur / part
        if cur.is_symlink():
            return True
    return False


def _safe_existing_path(root: Path, rel_str: str) -> Path | None:
    rel = Path(rel_str)
    if rel.is_absolute() or ".." in rel.parts:
        return None
    if _has_symlink_component(root, rel):
        return None
    target = root / rel
    if not target.exists():
        return None
    try:
        if not target.resolve().is_relative_to(root.resolve()):
            return None
    except OSError:
        return None
    return target


def _is_git_repo_root(root: Path) -> bool:
    probe = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
    )
    if probe.returncode != 0:
        return False
    try:
        return Path(probe.stdout.strip()).resolve() == root.resolve()
    except OSError:
        return False


def _git_commit_exists(root: Path, sha: str) -> bool:
    probe = subprocess.run(
        ["git", "-C", str(root), "cat-file", "-e", f"{sha}^{{commit}}"],
        capture_output=True,
        text=True,
    )
    return probe.returncode == 0


def _files_under_path(root: Path, rel_str: str, use_git: bool) -> list[Path]:
    rel = Path(rel_str)
    if rel.is_absolute() or ".." in rel.parts:
        raise FeatureMapError(f"unsafe sourcePath outside repository root: {rel_str!r}")
    if _has_symlink_component(root, rel):
        raise FeatureMapError(f"refusing symlink in sourcePath {rel_str!r}")
    target = _safe_existing_path(root, rel_str)
    if target is None:
        return []
    if use_git:
        # Hash git-tracked files ONLY so untracked scratch files can never poison the digest.
        result = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--", rel_str],
            capture_output=True,
            check=True,
        )
        safe_files: list[Path] = []
        for raw in result.stdout.split(b"\0"):
            if not raw:
                continue
            tracked_rel = raw.decode("utf-8")
            tracked_path = Path(tracked_rel)
            if _has_symlink_component(root, tracked_path):
                raise FeatureMapError(f"refusing symlink in tracked source path {tracked_rel!r}")
            safe = _safe_existing_path(root, tracked_rel)
            if safe is None:
                candidate = root / tracked_path
                if candidate.exists() or candidate.is_symlink():
                    raise FeatureMapError(f"unsafe tracked source path {tracked_rel!r}")
                continue
            if safe.is_file():
                safe_files.append(safe)
        return sorted(safe_files)
    if target.is_file():
        return [target]
    if target.is_dir():
        found: list[Path] = []
        for dirpath, dirnames, filenames in os.walk(target, followlinks=False):
            current = Path(dirpath)
            dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and d != "target")
            for d in dirnames:
                sub = current / d
                if sub.is_symlink():
                    raise FeatureMapError(
                        f"refusing symlink directory under sourcePath {rel_str!r}: {sub.relative_to(root).as_posix()}"
                    )
            for fname in sorted(filenames):
                if fname.startswith("."):
                    continue
                fpath = current / fname
                rel_posix = fpath.relative_to(root).as_posix()
                if fpath.is_symlink() or _has_symlink_component(root, Path(rel_posix)):
                    raise FeatureMapError(f"refusing symlink under sourcePath {rel_str!r}: {rel_posix}")
                safe = _safe_existing_path(root, rel_posix)
                if safe is None:
                    raise FeatureMapError(f"unsafe source file under {rel_str!r}: {rel_posix}")
                found.append(safe)
        return sorted(found)
    return []


def compute_source_digest(root: Path, source_paths: list[str], *, use_git: bool | None = None) -> str:
    """Compute a deterministic `sha256:<hex>` digest over every file in `source_paths`."""
    if use_git is None:
        use_git = _is_git_repo_root(root)
    unique_files: dict[str, Path] = {}
    sorted_paths = sorted(set(source_paths))
    if use_git:
        valid_rels: list[str] = []
        for rel_str in sorted_paths:
            rel = Path(rel_str)
            if rel.is_absolute() or ".." in rel.parts:
                raise FeatureMapError(f"unsafe sourcePath outside repository root: {rel_str!r}")
            if _has_symlink_component(root, rel):
                raise FeatureMapError(f"refusing symlink in sourcePath {rel_str!r}")
            if _safe_existing_path(root, rel_str) is not None:
                valid_rels.append(rel_str)
        if valid_rels:
            # Batch one `git ls-files` call per feature; hash git-tracked files ONLY.
            result = subprocess.run(
                ["git", "-C", str(root), "ls-files", "-z", "--", *valid_rels],
                capture_output=True,
                check=True,
            )
            for raw in result.stdout.split(b"\0"):
                if not raw:
                    continue
                tracked_rel = raw.decode("utf-8")
                tracked_path = Path(tracked_rel)
                if _has_symlink_component(root, tracked_path):
                    raise FeatureMapError(f"refusing symlink in tracked source path {tracked_rel!r}")
                safe = _safe_existing_path(root, tracked_rel)
                if safe is None:
                    candidate = root / tracked_path
                    if candidate.exists() or candidate.is_symlink():
                        raise FeatureMapError(f"unsafe tracked source path {tracked_rel!r}")
                    continue
                if safe.is_file():
                    unique_files[safe.relative_to(root).as_posix()] = safe
    else:
        for rel_str in sorted_paths:
            for path in _files_under_path(root, rel_str, False):
                rel_posix = path.relative_to(root).as_posix()
                unique_files[rel_posix] = path
    digest = hashlib.sha256()
    for rel_posix in sorted(unique_files):
        file_hash = hashlib.sha256(unique_files[rel_posix].read_bytes()).hexdigest()
        digest.update(rel_posix.encode("utf-8"))
        digest.update(b"\0")
        digest.update(file_hash.encode("ascii"))
        digest.update(b"\n")
    return f"sha256:{digest.hexdigest()}"


def _load_coverage_subsystems(root: Path) -> dict[str, dict]:
    manifest_dir = root / COVERAGE_MANIFEST_DIR
    if not manifest_dir.is_dir():
        return {}
    coverage_manifest = _sibling("coverage_manifest")
    doc = coverage_manifest.load(manifest_dir)
    return {
        sub["id"]: sub
        for sub in doc.get("subsystems", [])
        if isinstance(sub, dict) and isinstance(sub.get("id"), str)
    }


def _invariant_cited_path(ref: str) -> str | None:
    if ":" not in ref:
        return None
    prefix, rest = ref.split(":", 1)
    if prefix not in ("theorem", "checker", "law"):
        return None
    if "::" in rest:
        return rest.split("::", 1)[0]
    if "#" in rest:
        return rest.split("#", 1)[0]
    return rest


def _command_repo_paths(root: Path, command: str) -> set[str]:
    found: set[str] = set()
    if not command.strip():
        return found
    try:
        tokens = shlex.split(command)
    except ValueError:
        tokens = command.split()
    for token in tokens:
        candidates = [token]
        if "=" in token:
            candidates.append(token.split("=", 1)[1])
        for cand in candidates:
            cand = cand.strip()
            if not cand or cand.startswith("-") or cand.startswith(("http://", "https://")):
                continue
            if cand == "target" or cand.startswith("target/"):
                continue
            if "/" not in cand and not cand.endswith(
                (".qnt", ".lean", ".rs", ".py", ".sh", ".json", ".toml", ".ts")
            ):
                continue
            if _safe_existing_path(root, cand) is not None:
                found.add(cand)
    return found


def _gate_artifact_paths(
    root: Path,
    gate_ids: set[str],
    gate_meta: dict[str, dict],
    coverage_subsystems: dict[str, dict],
) -> set[str]:
    found: set[str] = set()

    def add_if_safe_repo_path(cand: str) -> None:
        if not cand or cand == "target" or cand.startswith("target/"):
            return
        if _safe_existing_path(root, cand) is not None:
            found.add(cand)

    for gid in sorted(gate_ids):
        gate = gate_meta.get(gid)
        if not isinstance(gate, dict):
            continue
        cmd = gate.get("command")
        if isinstance(cmd, str):
            found.update(_command_repo_paths(root, cmd))
        for cls in gate.get("classifications", []):
            if not isinstance(cls, dict):
                continue
            sub_id = cls.get("subsystem")
            layer = cls.get("layer")
            if not isinstance(sub_id, str):
                continue
            sub = coverage_subsystems.get(sub_id)
            if not isinstance(sub, dict):
                continue
            layers = [layer] if layer in ("runtime", "model", "proof") else ["runtime", "model", "proof"]
            for lyr in layers:
                layer_obj = sub.get(lyr)
                if isinstance(layer_obj, dict):
                    for art in layer_obj.get("artifacts", []):
                        if isinstance(art, str):
                            add_if_safe_repo_path(art)
                    corr = layer_obj.get("correspondenceArtifact")
                    if isinstance(corr, str):
                        add_if_safe_repo_path(corr)
                    for lcmd in layer_obj.get("commands", []):
                        if isinstance(lcmd, str):
                            found.update(_command_repo_paths(root, lcmd))
                for claim in sub.get("obligationClaims", []):
                    if not isinstance(claim, dict):
                        continue
                    ev = claim.get("evidence", {})
                    if not isinstance(ev, dict):
                        continue
                    for item in ev.get(lyr, []):
                        if not isinstance(item, dict):
                            continue
                        art = item.get("artifact")
                        if isinstance(art, str):
                            add_if_safe_repo_path(art)
                        ecmd = item.get("command")
                        if isinstance(ecmd, str):
                            found.update(_command_repo_paths(root, ecmd))
    return found


def _feature_gate_ids(feature: dict) -> set[str]:
    gate_ids: set[str] = set()
    for surf in feature.get("surfaces", []):
        if isinstance(surf, str) and surf.startswith("gate:"):
            gate_ids.add(surf[len("gate:"):])
    for inv in feature.get("invariants", []):
        if isinstance(inv, str) and ":" not in inv:
            gate_ids.add(inv)
    return gate_ids


def _feature_digest_paths(
    root: Path,
    feature: dict,
    *,
    gate_meta: dict[str, dict] | None = None,
    coverage_subsystems: dict[str, dict] | None = None,
) -> list[str]:
    paths: set[str] = set(feature["sourcePaths"])
    gate_ids = _feature_gate_ids(feature)
    for inv in feature.get("invariants", []):
        if not isinstance(inv, str):
            continue
        cited = _invariant_cited_path(inv)
        if cited is not None:
            paths.add(cited)
    if gate_ids:
        if gate_meta is None:
            _, gate_meta = extract_gate_surfaces(root)
        if coverage_subsystems is None:
            coverage_subsystems = _load_coverage_subsystems(root)
        paths.update(_gate_artifact_paths(root, gate_ids, gate_meta, coverage_subsystems))
    return sorted(paths)


def compute_verification_digest(
    root: Path,
    feature: dict,
    *,
    use_git: bool | None = None,
    gate_meta: dict[str, dict] | None = None,
    coverage_subsystems: dict[str, dict] | None = None,
) -> str:
    """Compute a deterministic `sha256:<hex>` over `sourcePaths`, cited invariant files, gate definitions/artifacts, and contract."""
    gate_ids = _feature_gate_ids(feature)
    if gate_ids:
        if gate_meta is None:
            _, gate_meta = extract_gate_surfaces(root)
        if coverage_subsystems is None:
            coverage_subsystems = _load_coverage_subsystems(root)
    digest_paths = _feature_digest_paths(
        root,
        feature,
        gate_meta=gate_meta,
        coverage_subsystems=coverage_subsystems,
    )
    source_digest = compute_source_digest(root, digest_paths, use_git=use_git)
    cited_gates: dict[str, dict] = {}
    cited_subsystems: dict[str, dict] = {}
    if gate_ids and gate_meta is not None:
        cited_sub_ids: set[str] = set()
        for gid in sorted(gate_ids):
            gate = gate_meta.get(gid)
            if isinstance(gate, dict):
                cited_gates[gid] = gate
                for cls in gate.get("classifications", []):
                    if isinstance(cls, dict) and isinstance(cls.get("subsystem"), str):
                        cited_sub_ids.add(cls["subsystem"])
        if coverage_subsystems is not None:
            for sid in sorted(cited_sub_ids):
                sub = coverage_subsystems.get(sid)
                if isinstance(sub, dict):
                    cited_subsystems[sid] = sub
    contract = {
        "coverageSubsystems": cited_subsystems,
        "gates": cited_gates,
        "invariants": sorted(feature["invariants"]),
        "probe": feature["probe"],
        "surfaces": sorted(feature["surfaces"]),
    }
    contract_json = json.dumps(contract, sort_keys=True, separators=(",", ":")).encode("utf-8")
    digest = hashlib.sha256()
    digest.update(b"sources\0")
    digest.update(source_digest.encode("ascii"))
    digest.update(b"\ncontract\0")
    digest.update(contract_json)
    digest.update(b"\n")
    return f"sha256:{digest.hexdigest()}"


def staleness_info(
    root: Path,
    feature: dict,
    *,
    use_git: bool | None = None,
    gate_meta: dict[str, dict] | None = None,
    coverage_subsystems: dict[str, dict] | None = None,
) -> dict:
    if use_git is None:
        use_git = _is_git_repo_root(root)
    live_digest = compute_verification_digest(
        root,
        feature,
        use_git=use_git,
        gate_meta=gate_meta,
        coverage_subsystems=coverage_subsystems,
    )
    last = feature.get("lastVerified")
    if not last:
        return {
            "liveSourceDigest": live_digest,
            "recordedSourceDigest": None,
            "recordedCommitSha": None,
            "stale": True,
            "unverified": True,
            "reason": "never-verified",
        }
    recorded_digest = last["sourceDigest"]
    recorded_sha = last["commitSha"]
    missing_commit = bool(use_git and not _git_commit_exists(root, recorded_sha))
    changed = recorded_digest != live_digest
    unverified = feature["evidenceTier"] == "unverified"
    if missing_commit:
        reason = "missing-commit"
    elif changed:
        reason = "source-changed"
    elif unverified:
        reason = "tier-unverified"
    else:
        reason = "fresh"
    return {
        "liveSourceDigest": live_digest,
        "recordedSourceDigest": recorded_digest,
        "recordedCommitSha": recorded_sha,
        "stale": missing_commit or changed or unverified,
        "unverified": unverified,
        "reason": reason,
    }


