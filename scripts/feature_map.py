def _markdown_heading_slugs(text: str) -> set[str]:
    """Return GitHub heading anchor slugs from actual ATX Markdown headings outside fenced code and HTML comments."""
    slugs: set[str] = set()
    counts: dict[str, int] = {}
    fence_char: str | None = None
    fence_len = 0
    in_html_comment = False
    for raw_line in text.splitlines():
        if fence_char is not None:
            close_match = re.match(r"^ {0,3}(`{3,}|~{3,})[ \t]*$", raw_line)
            if close_match:
                marker = close_match.group(1)
                if marker[0] == fence_char and len(marker) >= fence_len:
                    fence_char = None
                    fence_len = 0
            continue
        line = raw_line
        if in_html_comment:
            end_idx = line.find("-->")
            if end_idx == -1:
                continue
            line = line[end_idx + 3 :]
            in_html_comment = False
        # Strip inline HTML comments and handle opening multi-line HTML comments.
        while "<!--" in line:
            start_idx = line.find("<!--")
            end_idx = line.find("-->", start_idx + 4)
            if end_idx == -1:
                line = line[:start_idx]
                in_html_comment = True
                break
            line = line[:start_idx] + line[end_idx + 3 :]
        fence_match = re.match(r"^ {0,3}(`{3,}|~{3,})", line)
        if fence_match:
            marker = fence_match.group(1)
            fence_char = marker[0]
            fence_len = len(marker)
            continue
        # Only 0-3 ASCII spaces may precede an ATX heading; leading tabs or 4+ spaces are indented code.
        heading_match = re.match(r"^ {0,3}#{1,6}[ \t]+(.+?)(?:[ \t]+#+[ \t]*)?$", line)
        if not heading_match:
            continue
        raw = heading_match.group(1)
        raw = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", raw)
        normalized = re.sub(r"[^a-z0-9 _\t-]", "", raw.lower()).strip()
        normalized = re.sub(r"\t", " ", normalized)
        base_slug = normalized.replace(" ", "-")
        if not base_slug:
            continue
        seen = counts.get(base_slug, 0)
        counts[base_slug] = seen + 1
        slugs.add(base_slug if seen == 0 else f"{base_slug}-{seen}")
    return slugs


def _mask_rust_strings(cleaned: str) -> str:
    """Replace contents of double-quoted Rust string literals with spaces while preserving line structure."""
    out: list[str] = []
    i = 0
    n = len(cleaned)
    while i < n:
        ch = cleaned[i]
        # Skip single-quoted char literals containing `"` or `\"` so they don't start a string.
        if ch == "'":
            if i + 2 < n and cleaned[i + 1] == '"' and cleaned[i + 2] == "'":
                out.append("' '")
                i += 3
                continue
            if i + 3 < n and cleaned[i + 1] == "\\" and cleaned[i + 2] == '"' and cleaned[i + 3] == "'":
                out.append("'  '")
                i += 4
                continue
        if ch == '"':
            out.append('"')
            i += 1
            while i < n:
                c = cleaned[i]
                if c == "\\" and i + 1 < n:
                    out.append("  ")
                    i += 2
                    continue
                if c == '"':
                    out.append('"')
                    i += 1
                    break
                out.append("\n" if c == "\n" else " ")
                i += 1
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def _strip_leading_rust_attrs(text: str) -> str:
    idx = 0
    n = len(text)
    while idx < n:
        while idx < n and text[idx].isspace():
            idx += 1
        if not (text.startswith("#[", idx) or text.startswith("#![", idx)):
            break
        depth = 0
        while idx < n:
            c = text[idx]
            if c == "[":
                depth += 1
            elif c == "]":
                depth -= 1
                if depth == 0:
                    idx += 1
                    break
            idx += 1
    return text[idx:].strip()


def _iter_rust_top_level_blocks(masked: str) -> list[tuple[str, str]]:
    """Yield top-level `(header, body)` pairs for brace-delimited Rust items."""
    blocks: list[tuple[str, str]] = []
    n = len(masked)
    i = 0
    header_start = 0
    paren = bracket = 0
    while i < n:
        ch = masked[i]
        if ch == "(":
            paren += 1
        elif ch == ")":
            paren = max(0, paren - 1)
        elif ch == "[":
            bracket += 1
        elif ch == "]":
            bracket = max(0, bracket - 1)
        elif ch == ";" and paren == 0 and bracket == 0:
            header_start = i + 1
        elif ch == "{" and paren == 0 and bracket == 0:
            header = masked[header_start:i].strip()
            try:
                body, close_idx = _extract_brace_block(masked, i)
            except FeatureMapError:
                break
            blocks.append((header, body))
            i = close_idx + 1
            header_start = i
            continue
        i += 1
    return blocks


def _rust_struct_fields(body: str) -> set[str]:
    fields: set[str] = set()
    buf: list[str] = []
    brace = paren = bracket = angle = 0
    for ch in body:
        if ch == "{":
            brace += 1
        elif ch == "}":
            brace = max(0, brace - 1)
        elif ch == "(":
            paren += 1
        elif ch == ")":
            paren = max(0, paren - 1)
        elif ch == "[":
            bracket += 1
        elif ch == "]":
            bracket = max(0, bracket - 1)
        elif ch == "<":
            angle += 1
        elif ch == ">":
            angle = max(0, angle - 1)
        elif ch == "," and brace == 0 and paren == 0 and bracket == 0 and angle == 0:
            seg = _strip_leading_rust_attrs("".join(buf))
            m = re.match(r"^(?:pub(?:\([^)]*\))?\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*:", seg)
            if m:
                fields.add(m.group(1))
            buf.clear()
            continue
        buf.append(ch)
    seg = _strip_leading_rust_attrs("".join(buf))
    m = re.match(r"^(?:pub(?:\([^)]*\))?\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*:", seg)
    if m:
        fields.add(m.group(1))
    return fields


def _rust_top_level_declared_items(body: str, *, kinds: tuple[str, ...]) -> set[str]:
    """Return top-level item names of `kinds` declared directly inside a Rust block (skipping nested `{ ... }`)."""
    items: set[str] = set()
    n = len(body)
    i = 0
    stmt_start = 0
    paren = bracket = 0
    kind_set = set(kinds)
    decl_re = re.compile(
        r"^(?:(?:pub(?:\([^)]*\))?|default|async|unsafe|extern(?:\s+\"[^\"]*\")?)\s+)*"
        r"(const\s+(?:unsafe\s+)?fn|fn|const|type|static|struct|enum|trait|mod)\s+([A-Za-z_][A-Za-z0-9_]*)\b"
    )
    macro_re = re.compile(r"^macro_rules!\s+([A-Za-z_][A-Za-z0-9_]*)\b")

    def record(raw_stmt: str) -> None:
        stmt = _strip_leading_rust_attrs(raw_stmt)
        if not stmt:
            return
        if "macro" in kind_set:
            macro_match = macro_re.match(stmt)
            if macro_match:
                items.add(macro_match.group(1))
                return
        match = decl_re.match(stmt)
        if not match:
            return
        raw_kind = match.group(1)
        kind = "fn" if raw_kind.endswith("fn") else raw_kind
        if kind in kind_set:
            items.add(match.group(2))

    while i < n:
        ch = body[i]
        if ch == "(":
            paren += 1
        elif ch == ")":
            paren = max(0, paren - 1)
        elif ch == "[":
            bracket += 1
        elif ch == "]":
            bracket = max(0, bracket - 1)
        elif ch == ";" and paren == 0 and bracket == 0:
            record(body[stmt_start:i])
            stmt_start = i + 1
        elif ch == "{" and paren == 0 and bracket == 0:
            record(body[stmt_start:i])
            try:
                _, close_idx = _extract_brace_block(body, i)
            except FeatureMapError:
                break
            i = close_idx + 1
            stmt_start = i
            continue
        i += 1
    return items


def _parse_rust_impl_target(header: str) -> str | None:
    """Extract the target type identifier of a Rust `impl` block header."""
    m = re.match(r"^(?:(?:unsafe|default)\s+)*impl\b", header)
    if not m:
        return None
    rest = header[m.end() :].lstrip()
    # Skip optional generic parameter list `<...>` right after `impl`.
    if rest.startswith("<"):
        depth = 0
        idx = 0
        while idx < len(rest):
            if rest[idx] == "<":
                depth += 1
            elif rest[idx] == ">":
                depth -= 1
                if depth == 0:
                    idx += 1
                    break
            idx += 1
        rest = rest[idx:].lstrip()
    # Truncate at top-level `where` and split at top-level `for` (outside `<...>`, `(...)`, `[...]`).
    angle = paren = bracket = 0
    where_pos: int | None = None
    for_pos: int | None = None
    i = 0
    n = len(rest)
    while i < n:
        ch = rest[i]
        if ch == "<":
            angle += 1
        elif ch == ">":
            angle = max(0, angle - 1)
        elif ch == "(":
            paren += 1
        elif ch == ")":
            paren = max(0, paren - 1)
        elif ch == "[":
            bracket += 1
        elif ch == "]":
            bracket = max(0, bracket - 1)
        elif angle == 0 and paren == 0 and bracket == 0:
            if rest.startswith("where", i) and (i == 0 or not (rest[i - 1].isalnum() or rest[i - 1] == "_")):
                end_kw = i + 5
                if end_kw == n or not (rest[end_kw].isalnum() or rest[end_kw] == "_"):
                    where_pos = i
                    break
            if rest.startswith("for", i) and (i == 0 or not (rest[i - 1].isalnum() or rest[i - 1] == "_")):
                end_kw = i + 3
                if end_kw == n or not (rest[end_kw].isalnum() or rest[end_kw] == "_"):
                    for_pos = i
        i += 1
    if where_pos is not None:
        rest = rest[:where_pos]
    target = rest[for_pos + 3 :] if for_pos is not None else rest
    target = target.strip()
    # Strip trailing generic arguments `<...>`.
    if target.endswith(">"):
        depth = 0
        idx = len(target) - 1
        while idx >= 0:
            if target[idx] == ">":
                depth += 1
            elif target[idx] == "<":
                depth -= 1
                if depth == 0:
                    target = target[:idx].strip()
                    break
            idx -= 1
    # Strip leading references/mut/lifetimes and take final path segment.
    target = re.sub(r"^(?:&\s*(?:'[A-Za-z_][A-Za-z0-9_]*\s+)?(?:mut\s+)?)+", "", target).strip()
    if not target or not re.fullmatch(r"(?:::)?[A-Za-z_][A-Za-z0-9_]*(?:::[A-Za-z_][A-Za-z0-9_]*)*", target):
        return None
    return target.rsplit("::", 1)[-1]


def _rust_qualified_symbol_exists(masked: str, parts: list[str]) -> bool:
    """Verify `parts` (e.g. `['ArtifactKind', 'Entity']`) is declared inside matching Rust scope."""
    head, rest = parts[0], parts[1:]
    for raw_header, body in _iter_rust_top_level_blocks(masked):
        header = _strip_leading_rust_attrs(raw_header)
        mod_match = re.match(r"^(?:pub(?:\([^)]*\))?\s+)?mod\s+([A-Za-z_][A-Za-z0-9_]*)\s*$", header)
        if mod_match and mod_match.group(1) == head:
            if len(rest) == 1:
                declared = _rust_top_level_declared_items(
                    body,
                    kinds=("fn", "const", "type", "static", "struct", "enum", "trait", "mod", "macro"),
                )
                if rest[0] in declared:
                    return True
            elif _rust_qualified_symbol_exists(body, rest):
                return True
            continue
        if len(rest) != 1:
            continue
        member = rest[0]
        enum_match = re.match(r"^(?:pub(?:\([^)]*\))?\s+)?enum\s+([A-Za-z_][A-Za-z0-9_]*)\b", header)
        if enum_match and enum_match.group(1) == head:
            variants = {v[0] for v in _parse_rust_enum_variants(body)}
            if member in variants:
                return True
            continue
        struct_match = re.match(r"^(?:pub(?:\([^)]*\))?\s+)?struct\s+([A-Za-z_][A-Za-z0-9_]*)\b", header)
        if struct_match and struct_match.group(1) == head:
            if member in _rust_struct_fields(body):
                return True
            continue
        trait_match = re.match(r"^(?:pub(?:\([^)]*\))?\s+)?(?:unsafe\s+)?trait\s+([A-Za-z_][A-Za-z0-9_]*)\b", header)
        if trait_match and trait_match.group(1) == head:
            if member in _rust_top_level_declared_items(body, kinds=("fn", "const", "type")):
                return True
            continue
        impl_target = _parse_rust_impl_target(header)
        if impl_target == head:
            if member in _rust_top_level_declared_items(body, kinds=("fn", "const", "type")):
                return True
    return False


def _symbol_in_file(text: str, symbol: str, *, sep: str, suffix: str) -> bool:
    if sep == "#":
        if suffix == ".md":
            return symbol.lower() in _markdown_heading_slugs(text)
        return False
    if sep == "::" and suffix == ".rs":
        cleaned = _strip_rust_comments(text)
        masked = _mask_rust_strings(cleaned)
        parts = symbol.split("::")
        if any(not part for part in parts):
            return False
        if len(parts) == 1:
            declared = _rust_top_level_declared_items(
                masked,
                kinds=("fn", "const", "type", "static", "struct", "enum", "trait", "mod", "macro"),
            )
            return parts[0] in declared
        return _rust_qualified_symbol_exists(masked, parts)
    whole = rf"(?<![A-Za-z0-9_]){re.escape(symbol)}(?![A-Za-z0-9_])"
    return bool(re.search(whole, text))


def _invariant_error(root: Path, ref: str, gate_ids: set[str]) -> str | None:
    if ":" in ref:
        prefix, rest = ref.split(":", 1)
        if prefix in ("theorem", "checker", "law"):
            sep = ""
            symbol_part: str | None = None
            if "::" in rest:
                path_part, symbol_part = rest.split("::", 1)
                sep = "::"
            elif "#" in rest:
                path_part, symbol_part = rest.split("#", 1)
                sep = "#"
            else:
                path_part = rest
            target = _safe_existing_path(root, path_part)
            if target is None:
                return f"invariant {ref!r}: cited path {path_part!r} does not exist"
            if symbol_part is not None:
                if not target.is_file():
                    return f"invariant {ref!r}: cited path {path_part!r} is not a file for symbol {symbol_part!r}"
                text = target.read_text(encoding="utf-8", errors="replace")
                if not _symbol_in_file(
                    text,
                    symbol_part,
                    sep=sep,
                    suffix=target.suffix.lower(),
                ):
                    return f"invariant {ref!r}: cited symbol {symbol_part!r} not found in {path_part!r}"
            return None
        return f"invariant {ref!r}: unknown ref prefix {prefix!r}"
    if ref not in gate_ids:
        return f"invariant {ref!r}: not found in {PROMOTED_GATES_PATH.as_posix()}"
    return None


def load_registry(root: Path = ROOT) -> tuple[dict[str, dict], dict[str, set[str]], dict[str, dict]]:
    """Load and validate all domain files under `registry/features/`, enforcing Laws 1 & 2."""
    schema_file = root / SCHEMA_PATH
    if not schema_file.is_file():
        raise FeatureMapError(f"missing schema: {SCHEMA_PATH.as_posix()}")
    schema = json.loads(schema_file.read_text(encoding="utf-8"))
    extracted, gate_meta = extract_all_surfaces(root)
    gate_ids = set(gate_meta)
    all_live_surfaces = set().union(*extracted.values()) if extracted else set()

    reg_dir = root / REGISTRY_DIR
    files = sorted(p for p in reg_dir.glob("*.json") if p.name != "schema.json")
    if not files:
        raise FeatureMapError(f"{REGISTRY_DIR.as_posix()}: no domain feature files found")

    errors: list[str] = []
    domains: dict[str, dict] = {}
    owners: dict[str, str] = {}
    claimed_surfaces: set[str] = set()
    use_git = _is_git_repo_root(root)

    for path in files:
        rel = path.relative_to(root).as_posix()
        try:
            doc = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as err:
            errors.append(f"{rel}: invalid JSON: {err}")
            continue
        before = len(errors)
        validate_schema(doc, schema, schema, rel, errors)
        if len(errors) != before:
            continue
        domain = doc["domain"]
        if path.stem != domain:
            errors.append(f"{rel}: file must be named {domain}.json")
        features = doc["features"]
        ids = [f["id"] for f in features]
        if ids != sorted(ids):
            errors.append(f"{rel}: features must be sorted by id")

        for feat in features:
            where = f"{rel}:{feat['id']}"
            if feat["id"] in owners:
                errors.append(f"{where}: id also used in {owners[feat['id']]}")
            owners[feat["id"]] = rel
            if feat["domain"] != domain:
                errors.append(f"{where}: domain {feat['domain']!r} does not match file domain {domain!r}")

            # Law 1 (dangling surface claims)
            for surf in feat["surfaces"]:
                if surf not in all_live_surfaces:
                    errors.append(f"{where}: [Law 1] claimed surface {surf!r} does not exist in auto-extracted surfaces")
                else:
                    claimed_surfaces.add(surf)

            # Law 2 (existing paths, invariants, and non-empty probe for implemented features)
            for sp in feat["sourcePaths"]:
                if _safe_existing_path(root, sp) is None:
                    errors.append(f"{where}: [Law 2] sourcePath {sp!r} does not exist")
            for sc in feat["specContracts"]:
                if _safe_existing_path(root, sc) is None:
                    errors.append(f"{where}: [Law 2] specContract {sc!r} does not exist")
            for inv in feat["invariants"]:
                inv_err = _invariant_error(root, inv, gate_ids)
                if inv_err:
                    errors.append(f"{where}: [Law 2] {inv_err}")

            if feat["status"] == "implemented":
                probe = feat["probe"]
                if not probe["drive"].strip():
                    errors.append(f"{where}: [Law 2] implemented feature must have non-empty probe.drive")
                if not probe["observableEndState"].strip():
                    errors.append(f"{where}: [Law 2] implemented feature must have non-empty probe.observableEndState")
                if not feat["sourcePaths"]:
                    errors.append(f"{where}: [Law 2] implemented feature must declare at least one sourcePath")

            last_verified = feat.get("lastVerified")
            if last_verified and use_git and not _git_commit_exists(root, last_verified["commitSha"]):
                errors.append(
                    f"{where}: [Law 2] lastVerified.commitSha {last_verified['commitSha']!r} does not exist in git history"
                )

        domains[domain] = doc

    # Law 1 (no orphan surface across every auto-extracted family)
    orphans = sorted(all_live_surfaces - claimed_surfaces)
    for orphan in orphans:
        errors.append(f"[Law 1] orphan live surface not claimed by any feature: {orphan}")

    if errors:
        raise FeatureMapError("\n".join(errors))
    return domains, extracted, gate_meta


