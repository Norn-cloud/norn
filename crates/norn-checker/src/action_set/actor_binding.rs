//! Ring 0 for trusted actor provenance (#1091, #1101).
//!
//! ACTOR-STAMP-1: a protected property is never written from caller input,
//! by a writer, or by an owned-row derivation. The only admitted write is a
//! create-only stamp: an input field whose sole derivation is the verified
//! principal ([`norn_ir::ACTOR_SUBJECT_STAMP`], `inputRequired: false`), so a
//! caller never supplies it and no update overwrites the recorded principal.
//!
//! ACTOR-INDEPENDENT-1: each `independentOf` property is a protected text
//! actor property, with no default and no lifecycle, of the existing target a
//! `fire_transition` reads. A guard covers the effective transition: every
//! action firing a guarded transition declares the same guard, and no
//! synchronous writer may fire it.

