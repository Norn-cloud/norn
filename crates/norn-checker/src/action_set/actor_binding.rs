/// One finding at an input schema property, escaped as JSON Pointer segments.
fn input_property_finding(
    code: &str,
    message: String,
    artifact: &ArtifactEnvelope,
    field: &str,
) -> Diagnostic {
    let mut diagnostic = finding(code, message, artifact, "");
    diagnostic.span = Some(Span::from_segments([
        "payload",
        "inputSchema",
        "properties",
        field,
    ]));
    diagnostic
}

/// The per-action findings: caller-writable protected properties, a writer
/// on a generated-key create, and each `independentOf` property.
pub(super) fn actor_binding_findings(
    artifact: &ArtifactEnvelope,
    root: &ActionRoot,
    model: &Model<'_>,
) -> Vec<Diagnostic> {
    let mut findings = Vec::new();
    let program = root.effect_program.as_ref();
    let kind = program.map(|program| program.target().object_kind);
    let view = kind.and_then(|kind| model.effective_object_type_named(kind));
    let protected = |field: &str| {
        view.and_then(|view| view.property(field))
            .is_some_and(EffectiveProperty::protected)
    };
    if let (Some(ActionEffectProgram::UpsertInputObject { write_mode, .. }), Some(kind)) =
        (program, kind)
    {
        // CREATE-WRITER-1: a generated key's allocation is not qualified with a writer.
        if root.synchronous_rule.is_some()
            && view.is_some_and(|view| view.keys.iter().any(|key| key.naming_series.is_some()))
        {
            findings.push(finding(
                "action.validation.invalid_payload",
                format!("synchronousRule cannot compose with a create of {kind:?}, whose key is generated by a naming series"),
                artifact,
                "/payload/synchronousRule",
            ));
        }
        if let Some(JsonValue::Object(properties)) = root.input_schema.get("properties") {
            let stamped = root.actor_stamped_fields();
            for field in properties.keys().filter(|field| protected(field.as_str())) {
                let message = match (stamped.contains(field), write_mode) {
                    (true, UpsertWriteMode::CreateOnly) => continue,
                    (
                        true,
                        UpsertWriteMode::Upsert
                        | UpsertWriteMode::DraftOnly { .. }
                        | UpsertWriteMode::UpdateOnly,
                    ) => format!(
                        "the stamp of protected property {field:?} of {kind:?} requires writeMode create_only; an update would overwrite the recorded principal"
                    ),
                    (false, _) => format!(
                        "the upsert writes input property {field:?}, a protected actor property of {kind:?}, from caller input; stamp it from the verified principal instead (derive {:?} with inputRequired false, `fromCaller`)",
                        norn_ir::ACTOR_SUBJECT_STAMP
                    ),
                };
                findings.push(input_property_finding(
                    codes::TARGET_NOT_WRITABLE,
                    message,
                    artifact,
                    field,
                ));
            }
        }
    }
    let transition = matches!(program, Some(ActionEffectProgram::FireTransition { .. }));
    let mut seen = BTreeSet::new();
    for (index, property) in root.independent_of.iter().enumerate() {
        let resolved = view.and_then(|view| view.property(property.as_str()));
        let lifecycle = view.is_some_and(|view| view.lifecycle(property.as_str()).is_some());
        let first = seen.insert(property.as_str());
        if let Some(reason) = independent_actor_reason(transition, first, resolved, lifecycle) {
            findings.push(finding(
                codes::INDEPENDENT_ACTOR,
                format!("independentOf {:?} {reason}", property.as_str()),
                artifact,
                &format!("/payload/independentOf/{index}"),
            ));
        }
    }
    findings
}

/// ACTOR-INDEPENDENT-1: why one `independentOf` property cannot prove that
/// the verified principal differs from the recorded actor, if it cannot. Only
/// the kernel's create stamp may put a value there: a default, a lifecycle
/// initialization or a computed value would be indistinguishable from it.
fn independent_actor_reason(
    transition: bool,
    first: bool,
    resolved: Option<&EffectiveProperty>,
    lifecycle: bool,
) -> Option<&'static str> {
    if !transition {
        return Some(
            "requires a fire_transition effect: only an existing target records a prior actor",
        );
    }
    if !first {
        return Some("names the property twice");
    }
    let Some(property) = resolved else {
        return Some("names no stored property of the effect target");
    };
    if property.computed {
        return Some(
            "names a computed property, which holds no recorded principal and would refuse every call",
        );
    }
    if property.default.is_some() {
        return Some(
            "names a property with a declared or inherited default, a value no principal stamped",
        );
    }
    if lifecycle {
        return Some("names a lifecycle property, whose initial state no principal stamped");
    }
    if !property.protected() {
        return Some(
            "names a property a caller, import or update can write; only a protected actor property (a server-stamped principal) proves independence",
        );
    }
    if matches!(
        property.kind,
        EffectiveKind::Base(norn_ir::PropertyType::Text { .. })
    ) {
        None
    } else {
        Some("names a protected property that is not text, so it cannot hold a principal id")
    }
}

/// The string members of a closed writer schema enum at `pointer`.
fn enum_strings<'v>(item: &'v serde_json::Value, pointer: &str) -> Option<Vec<&'v str>> {
    item.pointer(pointer)
        .and_then(serde_json::Value::as_array)
        .map(|values| {
            values
                .iter()
                .filter_map(serde_json::Value::as_str)
                .collect()
        })
}

/// ACTOR-STAMP-1 (Ring 0): a writer's closed fact schema never names a
/// protected property of a type it writes, through `values`, `patch` or a
/// scalar `set` (an unconstrained `set` property may name any of them). Only
/// the kernel's create stamp of the verified principal writes one.
pub(super) fn writer_protected_findings(
    artifact: &ArtifactEnvelope,
    writer: &serde_json::Value,
    model: &Model<'_>,
) -> Vec<Diagnostic> {
    let Some(item) = writer.pointer("/outputSchema/properties/facts/items/properties") else {
        return Vec::new();
    };
    let operations = enum_strings(item, "/op/enum").unwrap_or_default();
    let set_properties = enum_strings(item, "/property/enum");
    let mut findings = Vec::new();
    for kind in enum_strings(item, "/objectType/enum").unwrap_or_default() {
        let Some(view) = model.effective_object_type_named(kind) else {
            continue;
        };
        let protected = |name: &str| {
            view.property(name)
                .is_some_and(EffectiveProperty::protected)
        };
        let mut named: BTreeSet<String> = ["values", "patch"]
            .iter()
            .filter_map(|member| item.get(*member)?.get("properties")?.as_object())
            .flat_map(serde_json::Map::keys)
            .filter(|name| protected(name.as_str()))
            .cloned()
            .collect();
        if operations.contains(&"set") {
            if let Some(names) = &set_properties {
                named.extend(
                    names
                        .iter()
                        .copied()
                        .filter(|name| protected(name))
                        .map(str::to_owned),
                );
            } else {
                named.extend(
                    view.properties
                        .iter()
                        .filter(|property| property.protected())
                        .map(|property| property.id.as_str().to_owned()),
                );
            }
        }
        for name in named {
            findings.push(finding(
                codes::TARGET_NOT_WRITABLE,
                format!(
                    "synchronousRule may write {name:?}, a protected property of {kind:?}; only the kernel's create stamp of the verified principal writes it"
                ),
                artifact,
                "/payload/synchronousRule",
            ));
        }
    }
    findings
}

/// A transition one action guards with `independentOf`.
struct Guard<'a> {
    /// The guarding action's artifact; `None` when it is already installed.
    artifact: Option<&'a ArtifactEnvelope>,
    action: &'a str,
    kind: &'a str,
    lifecycle: &'a str,
    transition: &'a str,
    properties: &'a [PropertyId],
}

/// Whether one type is the other or extends it, in either direction.
fn related(model: &Model<'_>, left: &str, right: &str) -> bool {
    let extends = |name: &str, ancestor: &str| {
        name == ancestor
            || model
                .effective_object_type_named(name)
                .is_some_and(|view| view.lineage.iter().any(|item| item.as_str() == ancestor))
    };
    extends(left, right) || extends(right, left)
}

/// The guard `root` declares, if it fires a transition with `independentOf`.
fn guard_of<'a>(artifact: Option<&'a ArtifactEnvelope>, root: &'a ActionRoot) -> Option<Guard<'a>> {
    match &root.effect_program {
        Some(ActionEffectProgram::FireTransition {
            object_kind,
            lifecycle,
            transition,
            ..
        }) if !root.independent_of.is_empty() => Some(Guard {
            artifact,
            action: root.action_id.as_str(),
            kind: object_kind.as_str(),
            lifecycle: lifecycle.as_str(),
            transition: transition.as_str(),
            properties: &root.independent_of,
        }),
        Some(_) | None => None,
    }
}

/// ACTOR-INDEPENDENT-1 over the whole effective action set (Astra ruling on
/// #1101): a guarded effective transition is guarded for every caller. Every
/// action that fires a guarded transition of a related type declares each
/// guarded property, and no synchronous writer may fire a guarded
/// transition. Candidate and installed actions are checked against every
/// guard in both directions, so the admission order cannot route around it:
/// a conflict is reported on the candidate side (the unguarded candidate, or
/// the candidate guard that an installed action or writer would bypass).
/// Each firing action resolves type names through its own scoped view
/// (#1376).
pub(super) fn transition_guard_findings(
    actions: &[(&ArtifactEnvelope, ActionRoot)],
    artifacts: &[ArtifactEnvelope],
    base: &[ArtifactEnvelope],
    views: &mut ScopedViews<'_>,
) -> Vec<Diagnostic> {
    let installed: Vec<(&ArtifactEnvelope, ActionRoot)> = base
        .iter()
        .filter_map(|artifact| decode_action(artifact).map(|root| (artifact, root)))
        .collect();
    // Every action with its artifact, and whether it is a candidate.
    let all: Vec<(&ArtifactEnvelope, &ActionRoot, bool)> = actions
        .iter()
        .map(|(artifact, root)| (*artifact, root, true))
        .chain(
            installed
                .iter()
                .map(|(artifact, root)| (*artifact, root, false)),
        )
        .collect();
    let guards: Vec<Guard<'_>> = all
        .iter()
        .filter_map(|(artifact, root, candidate)| guard_of(candidate.then_some(*artifact), root))
        .collect();
    let mut findings = Vec::new();
    for (artifact, root, candidate) in &all {
        let model = views.of(artifact).model();
        for guard in guards
            .iter()
            .filter(|guard| fires_unguarded(root, guard, model))
        {
            let message = format!(
                "action {:?} fires {:?} transition {:?} without independentOf {:?}, which action {:?} guards; every action firing it declares the same guard",
                root.action_id, guard.kind, guard.transition, guard.properties, guard.action
            );
            if let Some(at) = attribution(*candidate, artifact, guard) {
                findings.push(finding(
                    codes::INDEPENDENT_ACTOR,
                    message,
                    at,
                    "/payload/independentOf",
                ));
            }
        }
        for guard in writer_fired_guards(root, &guards, artifacts, base, model) {
            let message = format!(
                "action {:?} has a synchronousRule that may fire {:?} transition {:?}, which action {:?} guards with independentOf; a writer cannot fire a guarded transition",
                root.action_id, guard.kind, guard.transition, guard.action
            );
            let pointer = if *candidate {
                "/payload/synchronousRule"
            } else {
                "/payload/independentOf"
            };
            if let Some(at) = attribution(*candidate, artifact, guard) {
                findings.push(finding(codes::INDEPENDENT_ACTOR, message, at, pointer));
            }
        }
    }
    findings
}

/// The candidate artifact a conflict between `root` and `guard` is reported
/// on: `root` itself when it is a candidate, else the candidate guard. Two
/// installed sides were admitted together already.
fn attribution<'a>(
    candidate: bool,
    artifact: &'a ArtifactEnvelope,
    guard: &Guard<'a>,
) -> Option<&'a ArtifactEnvelope> {
    if candidate {
        Some(artifact)
    } else {
        guard.artifact
    }
}

/// Whether `root` fires the transition `guard` guards without every guarded property.
fn fires_unguarded(root: &ActionRoot, guard: &Guard<'_>, model: &Model<'_>) -> bool {
    let Some(ActionEffectProgram::FireTransition {
        object_kind,
        lifecycle,
        transition,
        ..
    }) = &root.effect_program
    else {
        return false;
    };
    guard.lifecycle == lifecycle.as_str()
        && guard.transition == transition.as_str()
        && related(model, guard.kind, object_kind)
        && guard
            .properties
            .iter()
            .any(|property| !root.independent_of.contains(property))
}

/// The guards a synchronous writer of `root` may fire.
fn writer_fired_guards<'g, 'a>(
    root: &ActionRoot,
    guards: &'g [Guard<'a>],
    artifacts: &[ArtifactEnvelope],
    base: &[ArtifactEnvelope],
    model: &Model<'_>,
) -> Vec<&'g Guard<'a>> {
    let Some(writer) = synchronous_writer_payload(root, artifacts, base) else {
        return Vec::new();
    };
    let Some(item) = writer.pointer("/outputSchema/properties/facts/items/properties") else {
        return Vec::new();
    };
    if !enum_strings(item, "/op/enum").is_some_and(|ops| ops.contains(&"transition")) {
        return Vec::new();
    }
    let kinds = enum_strings(item, "/objectType/enum").unwrap_or_default();
    let lifecycles = enum_strings(item, "/lifecycle/enum");
    let transitions = enum_strings(item, "/transition/enum");
    guards
        .iter()
        .filter(|guard| {
            kinds.iter().any(|kind| related(model, guard.kind, kind))
                && lifecycles
                    .as_ref()
                    .is_none_or(|names| names.contains(&guard.lifecycle))
                && transitions
                    .as_ref()
                    .is_none_or(|names| names.contains(&guard.transition))
        })
        .collect()
}

