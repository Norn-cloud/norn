//! The generated registry packs (`registry/packs/*/artifacts`) validate as
//! one ontology registry, and every link resolves and accounts for its
//! source pack's terms.

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use norn_checker::{
    ArtifactValidation, LinkCoverage, validate_link_registry, validate_ontology_registry,
};
use norn_ir::ArtifactEnvelope;

fn artifacts() -> Vec<ArtifactEnvelope> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../registry/packs");
    let mut paths: Vec<PathBuf> = fs::read_dir(&root)
        .expect("registry/packs exists")
        .flat_map(|pack| {
            fs::read_dir(pack.expect("entry").path().join("artifacts"))
                .into_iter()
                .flatten()
        })
        .map(|entry| entry.expect("artifact entry").path())
        .collect();
    paths.sort();
    paths
        .iter()
        .map(|path| {
            let text = fs::read_to_string(path).expect("artifact is readable");
            let artifact: ArtifactEnvelope =
                serde_json::from_str(&text).expect("artifact envelope");
            let validated = artifact.validate();
            assert!(validated.is_ok(), "{}: {validated:#?}", path.display());
            artifact
        })
        .collect()
}

fn coverage(link: &str) -> LinkCoverage {
    validate_link_registry(&artifacts())
        .expect("every link resolves")
        .into_iter()
        .find(|coverage| coverage.link_id == link)
        .expect("link is in the registry")
}

#[test]
fn registry_packs_form_one_ontology_registry() {
    let packs: Vec<_> = artifacts()
        .iter()
        .map(|artifact| artifact.payload.to_json_value())
        .filter(|payload| {
            payload
                .as_object()
                .and_then(|p| p.get("packKind"))
                .and_then(|k| k.as_string())
                == Some("ontology")
        })
        .collect();
    assert!(packs.len() >= 2);
    validate_ontology_registry(&packs).expect("terms are globally unique and resolve");
}

#[test]
fn erpnext_link_accounts_for_every_term() {
    let coverage = coverage("norn.link.erpnext.canon");
    let accounted = coverage.mapped.len() + coverage.residual.len() + coverage.canon_gaps.len();
    assert_eq!(accounted, coverage.active_terms);
    assert!(
        coverage
            .canon_gaps
            .contains("norn.erpnext.item.valuation.method")
    );
}

/// The projection report: per system, what maps (by relation), what is
/// residual system detail, and what the canon lacks. Generated from link
/// coverage; `NORN_PACKS_UPDATE=1` rewrites `registry/packs/PROJECTION.md`.
fn render(coverages: &[LinkCoverage]) -> String {
    let mut out = String::from(
        "# Projection of system packs onto the canon\n\n\
         Generated by `crates/norn-checker/tests/registry_packs.rs` from the link packs in\n\
         `registry/packs`; do not edit. Regenerate with `NORN_PACKS_UPDATE=1 cargo test -p norn-checker --test registry_packs`.\n\n\
         Evidence level: declared (reviewed correspondences over pinned schemas and docs). Nothing here is a parity or behaviour claim.\n\n\
         | Link | Terms | Mapped | Residual | Canon gaps |\n| --- | ---: | ---: | ---: | ---: |\n",
    );
    for c in coverages {
        writeln!(
            out,
            "| `{}` | {} | {} | {} | {} |",
            c.link_id,
            c.active_terms,
            c.mapped.len(),
            c.residual.len(),
            c.canon_gaps.len()
        )
        .expect("write to a String");
    }
    for c in coverages {
        writeln!(
            out,
            "\n## `{}`\n\n`{}` → `{}`\n\n### Maps\n",
            c.link_id, c.from_pack, c.to_pack
        )
        .expect("write to a String");
        for (term, targets) in &c.mapped {
            for (relation, to) in targets {
                let to: Vec<String> = to.iter().map(|t| format!("`{t}`")).collect();
                writeln!(out, "- `{term}` {relation} {}", to.join(", "))
                    .expect("write to a String");
            }
        }
        for (title, terms) in [
            ("Residual (system-specific)", &c.residual),
            ("Missing from the canon", &c.canon_gaps),
        ] {
            writeln!(out, "\n### {title}\n").expect("write to a String");
            if terms.is_empty() {
                out.push_str("None.\n");
            }
            for term in terms {
                writeln!(out, "- `{term}`").expect("write to a String");
            }
        }
    }
    out
}

#[test]
fn projection_report_is_current() {
    let mut coverages = validate_link_registry(&artifacts()).expect("every link resolves");
    coverages.sort_by(|a, b| a.link_id.cmp(&b.link_id));
    let rendered = render(&coverages);
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../registry/packs/PROJECTION.md");
    if std::env::var_os("NORN_PACKS_UPDATE").is_some() {
        fs::write(&path, &rendered).expect("write the projection report");
    }
    let committed = fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == rendered,
        "registry/packs/PROJECTION.md is stale; regenerate with NORN_PACKS_UPDATE=1\n---BEGIN---\n{rendered}---END---"
    );
}

#[test]
fn shopify_order_carries_both_the_commitment_and_the_claim() {
    // The input of the Shopify composition conflict handed to lane C: one
    // source term subsumed by two canon classes the core keeps apart.
    let coverage = coverage("norn.link.shopify.canon");
    let order = &coverage.mapped["norn.shopify.order"];
    let targets: Vec<&str> = order
        .iter()
        .flat_map(|(_, to)| to.iter().map(String::as_str))
        .collect();
    assert_eq!(targets, ["norn.commerce.order", "norn.core.claim"]);
}
