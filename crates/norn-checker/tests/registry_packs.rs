/// The projection report: per system, what maps (by relation), what is
/// residual system detail, and what the canon lacks. Generated from link
/// coverage; `NORN_PACKS_UPDATE=1` rewrites `registry/packs/PROJECTION.md`.
fn render(coverages: &[LinkCoverage]) -> String {
    let mut out = String::from(
        "# Projection of system packs onto the canon\n\n\
         Generated by `crates/norn-checker/tests/registry_packs.rs` from the link packs in\n\
         `registry/packs`; do not edit. Regenerate with `NORN_PACKS_UPDATE=1 cargo test -p norn-checker --test suites registry_packs::`.\n\n\
         Evidence level: declared (reviewed correspondences over pinned schemas and docs). Nothing here is a parity or behaviour claim.\n\n\
         | Link | Terms | Mapped | Residual | Canon gaps | Non-conforming |\n| --- | ---: | ---: | ---: | ---: | ---: |\n",
    );
    for c in coverages {
        writeln!(
            out,
            "| `{}` | {} | {} | {} | {} | {} |",
            c.link_id,
            c.active_terms,
            c.mapped.len(),
            c.residual.len(),
            c.canon_gaps.len(),
            c.non_conforming.len()
        )
        .expect("write to a String");
    }
    for c in coverages {
        writeln!(
            out,
            "\n## `{}`\n\n`{}` → `{}`\n\n### Maps\n",
            c.link_id, c.from_pack, c.to_pack
        )
        .expect("write to a String");
        for (term, targets) in &c.mapped {
            for (relation, to) in targets {
                let to: Vec<String> = to.iter().map(|t| format!("`{t}`")).collect();
                writeln!(out, "- `{term}` {relation} {}", to.join(", "))
                    .expect("write to a String");
            }
        }
        for (title, terms) in [
            ("Residual (system-specific)", &c.residual),
            ("Missing from the canon", &c.canon_gaps),
            (
                "Non-conforming source behaviour (breaks a canon law; flagged, never mapped)",
                &c.non_conforming,
            ),
        ] {
            writeln!(out, "\n### {title}\n").expect("write to a String");
            if terms.is_empty() {
                out.push_str("None.\n");
            }
            for term in terms {
                writeln!(out, "- `{term}`").expect("write to a String");
            }
        }
    }
    out
}

#[test]
fn projection_report_is_current() {
    let mut coverages = validate_link_registry(&artifacts()).expect("every link resolves");
    coverages.sort_by(|a, b| a.link_id.cmp(&b.link_id));
    let rendered = render(&coverages);
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../registry/packs/PROJECTION.md");
    if std::env::var_os("NORN_PACKS_UPDATE").is_some() {
        fs::write(&path, &rendered).expect("write the projection report");
    }
    let committed = fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == rendered,
        "registry/packs/PROJECTION.md is stale; regenerate with NORN_PACKS_UPDATE=1\n---BEGIN---\n{rendered}---END---"
    );
}

#[test]
fn shopify_order_is_a_commitment_and_its_receivable_the_claim() {
    // Lead ruling 2026-10-31 (the Ruling case on #74): the order maps only to
    // the commitment; the receivable view it gives rise to is the claim.
    let coverage = coverage("norn.link.shopify.canon");
    let targets = |term: &str| -> Vec<String> {
        coverage.mapped[term]
            .iter()
            .flat_map(|(_, to)| to.iter().cloned())
            .collect()
    };
    assert_eq!(targets("norn.shopify.order"), ["norn.commerce.order"]);
    assert_eq!(
        targets("norn.shopify.order.receivable"),
        ["norn.core.claim"]
    );
    assert_eq!(
        targets("norn.shopify.order.gives.rise.to"),
        ["norn.core.commitment.gives.rise.to"]
    );
}

#[test]
fn odoo_moves_give_rise_to_transactions_and_draft_reset_is_non_conforming() {
    // Lead rulings 2026-10-31: an invoice gives rise to an accounting
    // transaction rather than being one; resetting a posted move to draft is
    // non-conforming source behaviour, flagged and never mapped.
    let coverage = coverage("norn.link.odoo.canon");
    let move_targets: Vec<&String> = coverage.mapped["norn.odoo.account.move"]
        .iter()
        .flat_map(|(_, to)| to)
        .collect();
    assert_eq!(move_targets, ["norn.finance.invoice"]);
    assert!(
        coverage
            .mapped
            .contains_key("norn.odoo.account.move.posting")
    );
    assert!(
        coverage
            .non_conforming
            .contains("norn.odoo.account.move.button.draft")
    );
}

