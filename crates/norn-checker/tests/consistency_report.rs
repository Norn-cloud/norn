//! The generated consistency report over `registry/packs`
//! (`registry/packs/CONSISTENCY.md` and `consistency-report.json`) is
//! current. `NORN_PACKS_UPDATE=1` rewrites both; a stale report fails and
//! prints what it should be.

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use norn_checker::consistency::{ChaseBudget, pack_consistency_report};
use norn_ir::ArtifactEnvelope;
use serde_json::Value;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../registry/packs")
}

fn artifacts() -> Vec<ArtifactEnvelope> {
    let mut paths: Vec<PathBuf> = fs::read_dir(root())
        .expect("registry/packs exists")
        .flat_map(|pack| {
            fs::read_dir(pack.expect("entry").path().join("artifacts"))
                .into_iter()
                .flatten()
        })
        .map(|entry| entry.expect("artifact entry").path())
        .collect();
    paths.sort();
    paths
        .iter()
        .map(|path| {
            serde_json::from_str(&fs::read_to_string(path).expect("readable")).expect("envelope")
        })
        .collect()
}

fn text(value: &Value) -> &str {
    value.as_str().unwrap_or_default()
}

fn render(report: &Value) -> String {
    let mut out = String::from(
        "# Consistency of the system packs against the canon\n\n\
         Generated by `crates/norn-checker/tests/consistency_report.rs` from `registry/packs`; do not edit.\n\
         Regenerate with `NORN_PACKS_UPDATE=1 cargo test -p norn-checker --test consistency_report`.\n\
         The same data, for tools and the UI, is `consistency-report.json` (`norn-consistency-report@1`).\n\n",
    );
    writeln!(out, "Scope: {}.\n", text(&report["scope"])).expect("write");
    out.push_str("| Link | Rules (system / link + canon hierarchy / canon) | Not lowered | Vacuous | Incompatible | Unpreserved | Totality gaps | Divergence |\n| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |\n");
    let links = report["links"].as_array().cloned().unwrap_or_default();
    let count = |link: &Value, name: &str| -> usize {
        link["obligations"]
            .as_array()
            .and_then(|all| all.iter().find(|o| o["obligation"] == name))
            .and_then(|o| o["findings"].as_array())
            .map_or(0, Vec::len)
    };
    for link in &links {
        let lowered = &link["lowered"];
        writeln!(
            out,
            "| `{}` | {} / {} / {} | {} | {} | {} | {} | {} | not evaluated |",
            text(&link["link"]),
            lowered["sourceRules"],
            lowered["mappingRules"],
            lowered["targetRules"],
            lowered["notLowered"].as_array().map_or(0, Vec::len),
            count(link, "non_vacuity"),
            count(link, "schema_incompatibility"),
            count(link, "unpreserved_constraint"),
            count(link, "mapping_totality"),
        )
        .expect("write");
    }
    for link in &links {
        writeln!(out, "\n## `{}`", text(&link["link"])).expect("write");
        for obligation in link["obligations"].as_array().cloned().unwrap_or_default() {
            writeln!(
                out,
                "\n### {}\n\nEvidence: {}.\n",
                text(&obligation["obligation"]),
                text(&obligation["evidence"])
            )
            .expect("write");
            let findings = obligation["findings"]
                .as_array()
                .cloned()
                .unwrap_or_default();
            if findings.is_empty() {
                out.push_str("No finding.\n");
            }
            for f in findings {
                writeln!(
                    out,
                    "- `{}` ({}): {}",
                    text(&f["code"]),
                    text(&f["severity"]),
                    text(&f["message"])
                )
                .expect("write");
            }
        }
        let not_lowered = link["lowered"]["notLowered"]
            .as_array()
            .cloned()
            .unwrap_or_default();
        if !not_lowered.is_empty() {
            out.push_str("\n### Not lowered\n\n");
            for n in not_lowered {
                writeln!(out, "- {}", text(&n)).expect("write");
            }
        }
    }
    out
}

#[test]
fn the_consistency_report_is_current() {
    let report =
        pack_consistency_report(&artifacts(), ChaseBudget::default()).expect("packs lower");
    let markdown = render(&report);
    let mut json = serde_json::to_string_pretty(&report).expect("json");
    json.push('\n');
    let (md_path, json_path) = (
        root().join("CONSISTENCY.md"),
        root().join("consistency-report.json"),
    );
    if std::env::var_os("NORN_PACKS_UPDATE").is_some() {
        fs::write(&md_path, &markdown).expect("writable");
        fs::write(&json_path, &json).expect("writable");
        return;
    }
    let current = fs::read_to_string(&md_path).ok() == Some(markdown.clone())
        && fs::read_to_string(&json_path).ok() == Some(json.clone());
    assert!(
        current,
        "registry/packs/CONSISTENCY.md or consistency-report.json is stale; regenerate with \
         `NORN_PACKS_UPDATE=1 cargo test -p norn-checker --test consistency_report`.\n\
         ===== CONSISTENCY.md =====\n{markdown}\n===== consistency-report.json =====\n{json}"
    );
}
