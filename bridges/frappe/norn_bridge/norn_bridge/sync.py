"""Apply the staged projection bundle during `bench migrate` (#1085 §2).

The bundle is data generated by Norn. Sync upserts the records it contains,
prunes generated records it no longer contains, and records the applied
bundle hash. It owns only records in the `Norn Generated` module and the
names the bundle lists; it never edits anything else.
"""

from __future__ import annotations

import copy
import json
import os

import frappe

from norn_bridge import bundle

MODULE = "Norn Generated"


def stage(path: str) -> str:
    """`bench --site S execute norn_bridge.sync.stage --args '["file"]'`."""
    with open(path, encoding="utf-8") as handle:
        document = json.load(handle)
    _verify(document)
    os.makedirs(bundle.site_dir(), exist_ok=True)
    _write(bundle.path("staged"), document)
    return document["bundleHash"]


def after_migrate():
    staged = bundle.load("staged")
    if staged is None:
        return
    installed = bundle.load("installed") or {}
    present = all(frappe.db.exists("DocType", d["name"]) for d in staged.get("doctypes", []))
    if installed.get("bundleHash") == staged["bundleHash"] and present:
        print(f"norn_bridge: bundle {staged['bundleHash'][:12]} already applied")
        return
    apply(staged)


def status() -> dict:
    """`bench --site S execute norn_bridge.sync.status`: what is installed."""
    from frappe.model.base_document import get_controller

    installed = bundle.load("installed") or {}
    controllers = {}
    for name in frappe.get_all("DocType", {"module": MODULE}, pluck="name"):
        try:
            cls = get_controller(name)
            controllers[name] = f"{cls.__module__}.{cls.__name__} <- {cls.__mro__[1].__module__}.{cls.__mro__[1].__name__}"
        except Exception as error:  # reported, not hidden
            controllers[name] = f"{type(error).__name__}: {error}"
    return {
        "bundleHash": installed.get("bundleHash"),
        "doctypes": controllers,
        "workflows": frappe.get_all("Workflow", {"document_type": ["in", list(controllers) or [""]]}, ["name", "document_type", "is_active"]),
    }


def _verify(document: dict) -> None:
    if document.get("format") != bundle.FORMAT:
        frappe.throw(f"not a {bundle.FORMAT} bundle")
    if document.get("bundleHash") != bundle.digest(document):
        frappe.throw("bundle hash does not match its content")


def _write(file: str, document: dict) -> None:
    tmp = f"{file}.tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        json.dump(document, handle, indent=1, sort_keys=True)
    os.replace(tmp, file)


def apply(document: dict) -> None:
    _verify(document)
    previous = bundle.load("installed") or {}
    # The finder resolves controllers from the installed bundle, so it is
    # installed before the DocTypes that need it are imported.
    _write(bundle.path("installed"), document)
    for role in document.get("roles", []):
        _ensure("Role", role, {"role_name": role, "desk_access": 1})
    for state in document.get("workflowStates", []):
        _ensure("Workflow State", state, {"workflow_state_name": state})
    for action in document.get("workflowActions", []):
        _ensure("Workflow Action Master", action, {"workflow_action_name": action})
    wanted = {d["name"] for d in document.get("doctypes", [])}
    for doctype in document.get("doctypes", []):
        _import_doctype(copy.deepcopy(doctype))
    for workflow in document.get("workflows", []):
        _replace_workflow(copy.deepcopy(workflow))
    for name in frappe.get_all("DocType", {"module": MODULE}, pluck="name"):
        if name not in wanted:
            for workflow in frappe.get_all("Workflow", {"document_type": name}, pluck="name"):
                frappe.delete_doc("Workflow", workflow, force=True, ignore_permissions=True)
            frappe.delete_doc("DocType", name, force=True, ignore_permissions=True)
    frappe.db.commit()
    frappe.clear_cache()
    print(
        f"norn_bridge: applied bundle {document['bundleHash'][:12]}"
        f" (was {(previous.get('bundleHash') or 'none')[:12]}):"
        f" {len(wanted)} DocType(s), {len(document.get('workflows', []))} Workflow(s)"
    )


def _ensure(doctype: str, name: str, values: dict) -> None:
    if not frappe.db.exists(doctype, name):
        frappe.get_doc({"doctype": doctype, **values}).insert(ignore_permissions=True)


def _import_doctype(docdict: dict) -> None:
    from frappe.modules.import_file import import_doc

    if docdict.get("module") != MODULE or not docdict.get("is_virtual") or docdict.get("custom"):
        frappe.throw(f"{docdict.get('name')}: generated DocTypes are standard, virtual, in {MODULE}")
    import_doc(docdict, reset_permissions=True)


def _replace_workflow(docdict: dict) -> None:
    """Insert the Workflow without its controller hooks.

    Frappe's `Workflow.on_update` back-fills the state field with
    `UPDATE tab<DocType>`, which fails for a Virtual DocType (it has no
    table), and would create a Custom Field if the state field were missing.
    The generated DocType always declares the state field and the cell holds
    the states, so neither hook applies; the rows are written directly.
    """
    name = docdict["workflow_name"]
    if frappe.db.exists("Workflow", name):
        frappe.delete_doc("Workflow", name, force=True, ignore_permissions=True)
    doc = frappe.get_doc({"doctype": "Workflow", **docdict})
    doc.name = name
    doc.db_insert()
    for child in doc.get_all_children():
        child.parent = name
        child.parenttype = "Workflow"
        child.db_insert()
    frappe.cache.delete_value("workflow")
    frappe.clear_cache(doctype=docdict["document_type"])
