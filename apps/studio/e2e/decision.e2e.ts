import { expect, test } from "@playwright/test"
import { node, open, press } from "./canvas.ts"

// Rows "Ask a person" and "Option" of the automation canvas's verb matrix, and the decider's preview.
test("ask a person: create, view, edit, validate, undo/redo, save draft, reopen; preview follows every edit", async ({ page }) => {
  await open(page, "Automation")
  await page.getByRole("button", { name: "Ask a person", exact: true }).click()
  await expect(node(page, "decide")).toContainText("2 options")
  await expect(page.getByText("canvas.decision.no_question").first()).toBeVisible()
  const tree = page.getByTestId("decision-tree")
  await expect(tree).toContainText("No question yet")
  await page.getByLabel("Question", { exact: true }).fill("Refund the order?")
  await page.getByLabel("Question", { exact: true }).blur()
  await expect(tree).toContainText("Refund the order?")
  await expect(page.getByText("canvas.decision.no_question")).toHaveCount(0)
  await page.getByLabel("Risk").selectOption("high")
  await expect(tree).toContainText("high risk")
  await press(page, "z")
  await expect(tree).toContainText("medium risk")
  await press(page, "Shift+z")
  await expect(tree).toContainText("high risk")
  await press(page, "s")
  await page.reload()
  await page.getByRole("button", { name: "Automation", exact: true }).click()
  await node(page, "decide").click()
  await expect(page.getByTestId("decision-tree")).toContainText("Refund the order?")
})

test("option: create, edit, duplicate, reorder, delete, agent's pick, undo; the path summary and pre-answered note", async ({ page }) => {
  await open(page, "Automation")
  await page.getByRole("button", { name: "Ask a person", exact: true }).click()
  const tree = page.getByTestId("decision-tree")
  await page.getByLabel("Option 1 label").fill("Refund in full")
  await page.getByLabel("Option 1 label").blur()
  await page.getByLabel("Option 1 scope").fill("Card · the customer")
  await page.getByLabel("Option 1 scope").blur()
  await expect(tree).toContainText("Card · the customer")
  await page.getByRole("button", { name: "Option", exact: true }).click()
  await expect(node(page, "decide")).toContainText("3 options")
  await page.getByRole("button", { name: "Duplicate option 1" }).click()
  await expect(page.getByLabel("Option 2 label")).toHaveValue("Refund in full (copy)")
  await page.getByRole("button", { name: "Move option 2 down" }).click()
  await expect(page.getByLabel("Option 3 label")).toHaveValue("Refund in full (copy)")
  await page.getByRole("button", { name: "Delete option 3" }).click()
  await expect(node(page, "decide")).toContainText("3 options")
  await press(page, "z")
  await expect(node(page, "decide")).toContainText("4 options")
  await page.getByLabel("Agent's pick: option 1").check()
  await expect(tree.getByText("Agent's pick")).toHaveCount(1)
  await tree.getByRole("button", { name: /Refund in full\s/ }).first().click()
  await expect(tree).toContainText(/Then\s*1/)
  await expect(tree.getByTestId("pre-answered")).toHaveCount(0)
  await expect(tree.getByRole("button", { name: "Approve this path" })).toBeDisabled()
})

test("decision preview: a follow-up opens from the chosen option and is marked pre-answered", async ({ page }) => {
  await page.goto("/sheet.html?state=decision%2Fdefault")
  const tree = page.getByTestId("decision-tree")
  await tree.getByRole("button", { name: /Send a reminder/ }).click()
  await expect(tree).toContainText("Tell the account owner too?")
  await tree.getByRole("button", { name: /Only the reminder/ }).click()
  await expect(tree.getByTestId("pre-answered")).toBeVisible()
  await expect(tree.getByText("Agent's pick")).toHaveCount(2)
})
