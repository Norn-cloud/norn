import { expect, test } from "@playwright/test"
import { clear, clickEdge, drag, edge, edgeEnds, lefts, node, open, placed, press, shown } from "./canvas.ts"

// One test per row of the automation canvas's verb matrix (see the PR body).
const out = (page: Parameters<typeof node>[0], id: string, port: string) => node(page, id).locator(`.react-flow__handle[data-handleid="${port}"]`)
const into = (page: Parameters<typeof node>[0], id: string) => node(page, id).locator(".react-flow__handle-left")

test("step: create, view, edit, delete, duplicate, move, undo/redo, validate, save draft, reopen; start is fixed", async ({ page }) => {
  await open(page, "Automation")
  await expect(page.getByText("Checker: no findings")).toBeVisible()
  await page.getByRole("button", { name: "Wait", exact: true }).click()
  await expect(node(page, "sleep")).toContainText("60000 ms")
  await expect(node(page, "sleep")).toContainText("1 problem")
  await expect(page.getByText("canvas.flow.unreachable").first()).toBeVisible()
  await page.getByLabel("Wait (milliseconds)").fill("5000")
  await page.getByLabel("Wait (milliseconds)").blur()
  await expect(node(page, "sleep")).toContainText("5000 ms")
  const before = await (await shown(page, "sleep")).boundingBox()
  await (await shown(page, "sleep")).hover()
  await page.mouse.down(); // From the grab point (the card's centre), 150px right.
  await page.mouse.move((before?.x ?? 0) + (before?.width ?? 0) / 2 + 150, (before?.y ?? 0) + (before?.height ?? 0) / 2 + 60, { steps: 8 }); await page.mouse.up()
  expect((await node(page, "sleep").boundingBox())?.x).toBeGreaterThan((before?.x ?? 0) + 80)
  await (await shown(page, "sleep")).click()
  await press(page, "d")
  await expect(node(page, "sleep_copy")).toContainText("5000 ms")
  await page.keyboard.press("Delete")
  await expect(node(page, "sleep_copy")).toHaveCount(0)
  await press(page, "z")
  await expect(node(page, "sleep_copy")).toBeVisible()
  await press(page, "Shift+z")
  await expect(node(page, "sleep_copy")).toHaveCount(0)
  // The start cannot be deleted or copied, and deleting with it selected keeps its connection.
  await (await shown(page, "start")).click()
  await page.keyboard.press("Delete")
  await expect(node(page, "start")).toBeVisible()
  await expect(edge(page, "start.next")).toHaveCount(1)
  await press(page, "s")
  await expect(page.getByText(/Draft saved in this browser/)).toBeVisible()
  await expect(page.getByRole("button", { name: "Run in the cell" })).toBeDisabled()
  await page.reload()
  await page.getByRole("button", { name: "Automation", exact: true }).click()
  await expect(node(page, "sleep")).toContainText("5000 ms")
})

test("connection: create, view, delete, reconnect, undo/redo, validate, reopen", async ({ page }) => {
  await open(page, "Automation")
  // view + delete + validate: without overdue → open, the open outcome is unreachable.
  await clickEdge(page, "overdue.next")
  await expect(page.getByText(/Overdue \(next\) → Open/)).toBeVisible()
  await page.keyboard.press("Delete")
  await expect(edge(page, "overdue.next")).toHaveCount(0)
  await expect(node(page, "open")).toContainText("1 problem")
  await press(page, "z")
  await expect(edge(page, "overdue.next")).toHaveCount(1)
  await press(page, "Shift+z")
  await expect(edge(page, "overdue.next")).toHaveCount(0)
  // create: draw it again; the automation checks clean.
  await drag(page, out(page, "overdue", "next"), into(page, "open"))
  await expect(edge(page, "overdue.next")).toHaveCount(1)
  await expect(page.getByText("Checker: no findings")).toBeVisible()
  // reconnect: move its end onto remind, which already has an entry: a join the canvas names.
  await clickEdge(page, "overdue.next")
  await drag(page, edge(page, "overdue.next").locator(".react-flow__edgeupdater-target"), into(page, "remind"))
  await expect(page.getByText("canvas.flow.join").first()).toBeVisible()
  await press(page, "z")
  await expect(page.getByText("Checker: no findings")).toBeVisible()
  // validate through lowering: leaving by otherwise instead leaves the remind path without an outcome.
  await clickEdge(page, "overdue.next")
  await page.keyboard.press("Delete")
  await drag(page, out(page, "overdue", "otherwise"), into(page, "open"))
  await expect(edge(page, "overdue.otherwise")).toHaveCount(1)
  await expect(page.getByText("NORN-FLOW-RESULT").first()).toBeVisible()
  // reopen: the drawn connection and its finding come back after a reload.
  await page.reload()
  await page.getByRole("button", { name: "Automation", exact: true }).click()
  await expect(edge(page, "overdue.otherwise")).toHaveCount(1)
  await expect(page.getByText("NORN-FLOW-RESULT").first()).toBeVisible()
})

