import { expect, test } from "@playwright/test"
import { clickEdge, drag, edge, node, open, press } from "./canvas.ts"

// One test per row of the automation canvas's verb matrix (see the PR body).
const out = (page: Parameters<typeof node>[0], id: string, port: string) => node(page, id).locator(`.react-flow__handle[data-handleid="${port}"]`)
const into = (page: Parameters<typeof node>[0], id: string) => node(page, id).locator(".react-flow__handle-left")

test("step: create, view, edit, delete, duplicate, move, undo/redo, validate, save draft, reopen; start is fixed", async ({ page }) => {
  await open(page, "Automation")
  await expect(page.getByText("Checker: no findings")).toBeVisible()
  await page.getByRole("button", { name: "Wait", exact: true }).click()
  await expect(node(page, "sleep")).toContainText("60000 ms")
  await expect(node(page, "sleep")).toContainText("1 problem")
  await expect(page.getByText("canvas.flow.unreachable").first()).toBeVisible()
  await page.getByLabel("Wait (milliseconds)").fill("5000")
  await page.getByLabel("Wait (milliseconds)").blur()
  await expect(node(page, "sleep")).toContainText("5000 ms")
  const before = await node(page, "sleep").boundingBox()
  await node(page, "sleep").hover()
  await page.mouse.down(); await page.mouse.move((before?.x ?? 0) + 150, (before?.y ?? 0) + 60, { steps: 8 }); await page.mouse.up()
  expect((await node(page, "sleep").boundingBox())?.x).toBeGreaterThan((before?.x ?? 0) + 80)
  await node(page, "sleep").click()
  await press(page, "d")
  await expect(node(page, "sleep_copy")).toContainText("5000 ms")
  await page.keyboard.press("Delete")
  await expect(node(page, "sleep_copy")).toHaveCount(0)
  await press(page, "z")
  await expect(node(page, "sleep_copy")).toBeVisible()
  await press(page, "Shift+z")
  await expect(node(page, "sleep_copy")).toHaveCount(0)
  // The start cannot be deleted or copied.
  await node(page, "start").click()
  await page.keyboard.press("Delete")
  await expect(node(page, "start")).toBeVisible()
  await press(page, "s")
  await expect(page.getByText(/Draft saved in this browser/)).toBeVisible()
  await expect(page.getByRole("button", { name: "Run in the cell" })).toBeDisabled()
  await page.reload()
  await page.getByRole("button", { name: "Automation", exact: true }).click()
  await expect(node(page, "sleep")).toContainText("5000 ms")
})

test("connection: create, view, delete, reconnect, undo/redo, validate, reopen", async ({ page }) => {
  await open(page, "Automation")
  await clickEdge(page, "overdue.next")
  await expect(page.getByText(/Overdue \(next\) → Open/)).toBeVisible()
  await page.keyboard.press("Delete")
  await expect(edge(page, "overdue.next")).toHaveCount(0)
  await expect(node(page, "open")).toContainText("1 problem")
  await press(page, "z")
  await expect(edge(page, "overdue.next")).toHaveCount(1)
  await press(page, "Shift+z")
  await drag(page, out(page, "overdue", "otherwise"), into(page, "open"))
  await expect(edge(page, "overdue.otherwise")).toHaveCount(1)
  await expect(page.getByText("Checker: no findings")).toBeVisible()
  await clickEdge(page, "overdue.otherwise")
  await drag(page, edge(page, "overdue.otherwise").locator(".react-flow__edgeupdater-target"), into(page, "remind"))
  await expect(page.getByText("canvas.flow.join").first()).toBeVisible()
  await press(page, "z")
  await expect(page.getByText("Checker: no findings")).toBeVisible()
  await page.reload()
  await page.getByRole("button", { name: "Automation", exact: true }).click()
  await expect(edge(page, "overdue.otherwise")).toHaveCount(1)
})

test("tool binding: view, edit tool and inputs, undo/redo, validate, reopen", async ({ page }) => {
  await open(page, "Automation")
  await node(page, "remind").click()
  await expect(page.getByLabel("invoiceId (string)")).toHaveValue("invoice.id")
  await page.getByLabel("invoiceId (string)").fill("invoice.amountMinor")
  await page.getByLabel("invoiceId (string)").blur()
  await expect(page.getByText("NORN-FLOW-VALUE").first()).toBeVisible()
  await expect(node(page, "remind")).toContainText("problem")
  await press(page, "z")
  await expect(page.getByText("Checker: no findings")).toBeVisible()
  await press(page, "Shift+z")
  await expect(page.getByText("NORN-FLOW-VALUE").first()).toBeVisible()
  await page.getByLabel("Name its result").fill("reminder")
  await page.getByLabel("Name its result").blur()
  await page.getByLabel("Tool").selectOption("billing.load_invoice")
  await expect(node(page, "remind")).toContainText("billing.load_invoice")
  await page.reload()
  await page.getByRole("button", { name: "Automation", exact: true }).click()
  await node(page, "remind").click()
  await expect(page.getByLabel("Tool")).toHaveValue("billing.load_invoice")
  await expect(page.getByLabel("Name its result")).toHaveValue("reminder")
})

test("route branches: create, edit, delete, reorder, undo/redo, validate, reopen", async ({ page }) => {
  await open(page, "Automation")
  await node(page, "settled").click()
  await expect(page.getByLabel("Branch b0")).toHaveValue("invoice.status == paid")
  // reorder: b1 moves up and its exit follows it.
  await page.getByRole("button", { name: "Move b1 up" }).click()
  await expect(page.getByLabel("Branch b0")).toHaveValue("invoice.status == draft")
  await expect(edge(page, "settled.b1")).toContainText("b0")
  await expect(page.getByText("Checker: no findings")).toBeVisible()
  await press(page, "z")
  await expect(page.getByLabel("Branch b0")).toHaveValue("invoice.status == paid")
  // edit: a condition on a field the tool does not return is a typed finding.
  await page.getByLabel("Branch b0").fill("invoice.colour == red")
  await page.getByLabel("Branch b0").blur()
  await expect(page.getByTestId("problem").first()).toBeVisible()
  await press(page, "z")
  // create + delete: a new branch with no exit; deleting b0 leaves its outcome unreachable.
  await page.getByRole("button", { name: "Branch", exact: true }).click()
  await expect(page.getByLabel("Branch b2")).toBeVisible()
  await page.getByRole("button", { name: "Delete b0" }).click()
  await expect(node(page, "paid")).toContainText("problem")
  await press(page, "z")
  await expect(node(page, "paid")).not.toContainText("problem")
  await page.reload()
  await page.getByRole("button", { name: "Automation", exact: true }).click()
  await node(page, "settled").click()
  await expect(page.getByLabel("Branch b2")).toBeVisible()
})

