import { Database } from "bun:sqlite"
import { readFileSync } from "node:fs"
import { getMigrations } from "better-auth/db/migration"
import { authOptions } from "../worker/auth.ts"

/**
 * The D1 schema Better Auth needs for worker/auth.ts, from Better Auth's own
 * migration planner run against an empty SQLite database. The committed
 * migration (worker/migrations/0001_better_auth.sql) must equal this output;
 * test/auth-schema.test.ts fails on drift. Regenerate with
 * `bun scripts/auth-schema.ts > worker/migrations/0001_better_auth.sql`.
 */
export async function authSchemaSql(): Promise<string> {
  const options = authOptions({ database: new Database(":memory:"), secret: "schema-generation-only-not-a-secret", baseURL: "https://studio.invalid" })
  const { compileMigrations } = await getMigrations(options)
  return `-- Generated by scripts/auth-schema.ts from worker/auth.ts. Do not edit.\n${(await compileMigrations()).trim()}\n`
}

/**
 * What the assistants' OAuth server (MCP, `STUDIO_MCP=on`) adds to that schema, planned against a
 * database already holding 0001. Applied migrations are never edited, so it is its own file,
 * worker/migrations/0007_oauth_provider.sql; test/auth-schema.test.ts fails on drift. Regenerate
 * with `bun scripts/auth-schema.ts --oauth > worker/migrations/0007_oauth_provider.sql`.
 */
export async function oauthSchemaSql(): Promise<string> {
  const database = new Database(":memory:")
  database.exec(readFileSync(new URL("../worker/migrations/0001_better_auth.sql", import.meta.url), "utf8"))
  const options = authOptions({ database, secret: "schema-generation-only-not-a-secret", baseURL: "https://studio.invalid", mcp: true })
  const { compileMigrations } = await getMigrations(options)
  return `-- Generated by scripts/auth-schema.ts --oauth from worker/auth.ts. Do not edit.\n${(await compileMigrations()).trim()}\n`
}

if (import.meta.main) process.stdout.write(process.argv.includes("--oauth") ? await oauthSchemaSql() : await authSchemaSql())
