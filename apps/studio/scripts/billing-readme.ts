import { readFileSync, writeFileSync } from "node:fs"
import { BILLING_ENV, PLACEHOLDER_PLANS } from "../worker/billing.ts"

/**
 * The README's billing section, generated from worker/billing.ts so the documented settings and the
 * placeholder plan table are the code's own. worker/test/billing.test.ts fails on drift; regenerate
 * with `bun scripts/billing-readme.ts`.
 */
const START = "<!-- billing:start (generated by scripts/billing-readme.ts) -->"
const END = "<!-- billing:end -->"

const WHAT: Record<(typeof BILLING_ENV)[number], string> = {
  POLAR_ACCESS_TOKEN: "Organization Access Token (Polar → Settings → Developers); a Worker secret",
  POLAR_WEBHOOK_SECRET: "the webhook endpoint's signing secret (Polar → Settings → Webhooks); a Worker secret",
  POLAR_SERVER: "`sandbox` or `production`; tokens and products are separate per server",
  POLAR_PLANS: "the plan table as JSON: product ids and limits (below)",
}

export function billingSection(): string {
  return [
    START,
    "## Billing (Polar)",
    "",
    "Off unless all four settings are set: then every limit is unlimited and Polar is never called (self-hosting).",
    "Some but not all of them refuses to start. Limits are enforced on the server only; the browser renders `/api/billing`.",
    "",
    "| Setting | What |",
    "| --- | --- |",
    ...BILLING_ENV.map((name) => `| \`${name}\` | ${WHAT[name]} |`),
    "",
    "Webhook endpoint to register in Polar: `<studio origin>/api/auth/polar/webhooks` (subscription events).",
    "`null` is unlimited; `cells` counts the workspaces a person owns, `members` a workspace's members and pending invitations.",
    "PLACEHOLDER plan table (not decided prices or limits; the product ids are not real):",
    "",
    "```json",
    JSON.stringify(PLACEHOLDER_PLANS, null, 2),
    "```",
    END,
  ].join("\n")
}

export const README = new URL("../README.md", import.meta.url)

/** The README with its billing section regenerated (appended when it has none). */
export function withBillingSection(text: string): string {
  const start = text.indexOf(START)
  const end = text.indexOf(END)
  if (start === -1 || end === -1) return `${text.trimEnd()}\n\n${billingSection()}\n`
  return `${text.slice(0, start)}${billingSection()}${text.slice(end + END.length)}`
}

if (import.meta.main) writeFileSync(README, withBillingSection(readFileSync(README, "utf8")))
