/** A copy of a dashboard under a new title, with fresh tile ids. */
export function duplicateDashboard(dashboard: Dashboard, newId: () => string = () => crypto.randomUUID()): Dashboard {
  return { title: `${dashboard.title} (copy)`, tiles: dashboard.tiles.map((tile) => ({ ...structuredClone(tile), id: newId() })) }
}

/**
 * Where a cell finding on a dashboard belongs in the editor, from its JSON
 * pointer into the definition: the title, one tile, or the dashboard as a whole.
 */
export function dashboardField(pointer: string | null): string | null {
  const parts = (pointer ?? "").split("/").slice(1)
  const at = parts[0] === "payload" ? parts.slice(1) : parts
  if (at[0] === "title") return "title"
  if (at[0] === "tiles" && at[1] !== undefined && /^\d+$/.test(at[1])) return `tile.${at[1]}`
  if (at[0] === "tiles") return "tiles"
  return null
}

export type SaveResult =
  | { readonly saved: { readonly id: string; readonly version: number; readonly receipt: Receipt } }
  | { readonly findings: readonly Finding[] }
  | { readonly conflict: true }
  | { readonly signoff: "mismatch" | "unavailable"; readonly restatement?: Restatement }

/**
 * Save one dashboard as `id`: the cell admits it, then installs it as the
 * version after `expectedVersion` (a new definition without one). The cell's
 * refusal comes back as findings; a newer version as a conflict.
 */
export async function saveDashboard(store: DefinitionStore, id: string, dashboard: Dashboard, expectedVersion?: number, signoff?: string): Promise<SaveResult> {
  const admission = await store.admit(id, dashboard)
  if (!admission.admitted) return { findings: admission.findings }
  const result = await store.install(id, dashboard, expectedVersion, signoff)
  if (result.installed) return { saved: { id: result.id, version: result.version, receipt: result.receipt } }
  if ("conflict" in result) return { conflict: true }
  if ("signoff" in result) return { signoff: result.signoff, ...result.restatement ? { restatement: result.restatement } : {} }
  return { findings: result.findings }
}

/** Lower-case hex SHA-256 of the text's UTF-8 bytes: the digest a sign-off records. */
export async function sha256(text: string): Promise<string> {
  const bytes = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text))
  return Array.from(new Uint8Array(bytes), (byte) => byte.toString(16).padStart(2, "0")).join("")
}

/**
 * The dashboard in plain words, as the server states it (POST /api/dashboards/check): the title, then each tile
 * by number with its question's words. Generated by code from the payload, never by a model.
 */
export async function restateDashboard(dashboard: Dashboard, fetcher: Fetch = (input, init) => fetch(input, init)): Promise<Restatement> {
  const response = await fetcher("/api/dashboards/check", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ dashboard }) })
  const body = await response.json().catch(() => null) as { restatement?: Partial<Restatement> } | null
  const words = body?.restatement
  if (!response.ok || typeof words?.text !== "string" || typeof words.sha256 !== "string") throw new Error(response.status === 401 ? "Sign in again to sign off." : "The server could not state this dashboard in plain words.")
  return { text: words.text, sha256: words.sha256 }
}
